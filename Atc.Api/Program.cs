// Makes your application's types, such as OrderRepository, available here.
using Atc.Api;

// Provides access to information about an exception caught by
// ASP.NET Core's exception-handling middleware.
using Microsoft.AspNetCore.Diagnostics;

// Provides OracleException so Oracle errors can be identified.
using Oracle.ManagedDataAccess.Client;

// This is the application's startup file, typically Program.cs.
//
// Top-level statements let you write startup code without explicitly
// declaring a Program class and Main method.

// Creates the application builder.
//
// It prepares configuration, logging, dependency injection, and hosting.
// args contains command-line arguments passed to the application.
var builder = WebApplication.CreateBuilder(args);

// Registers support for API controllers and configures their JSON handling.
builder.Services.AddControllers().AddJsonOptions(options =>
    // Reject incoming JSON properties that do not exist on the target DTO.
    //
    // For example, "quanttyCompleted" would be rejected instead of
    // silently ignored because the actual property is QuantityCompleted.
    //
    // This does not require every DTO property to be supplied;
    // missing values are handled by defaults and validation rules.
    options.JsonSerializerOptions.UnmappedMemberHandling =
        System.Text.Json.Serialization.JsonUnmappedMemberHandling.Disallow);

// Registers services for generating an OpenAPI document.
//
// OpenAPI describes the API's routes, inputs, and responses.
// This does not itself add an interactive Swagger UI.
builder.Services.AddOpenApi();

// Registers services for standardized Problem Details error responses.
builder.Services.AddProblemDetails();

// Registers OrderRepository with dependency injection.
//
// Scoped means one instance per service scope—normally one HTTP request.
// Controllers in that request can receive the same repository instance.
//
// This does not open a database connection. The repository does that
// when one of its methods runs.
builder.Services.AddScoped<OrderRepository>();

// Check for the required database connection string before starting.
//
// GetConnectionString("Oracle") reads ConnectionStrings:Oracle.
//
// Possible configuration sources include:
//   Development user secrets: ConnectionStrings:Oracle
//   Environment variable:    ConnectionStrings__Oracle
//
// Double underscores represent nested configuration keys in
// environment-variable names.
if (string.IsNullOrWhiteSpace(
    builder.Configuration.GetConnectionString("Oracle")))
{
    // Stop startup with a clear message if configuration is missing.
    //
    // This only checks that a value exists; it does not test whether
    // the database is reachable or the credentials are correct.
    throw new InvalidOperationException(
        "Configure ConnectionStrings:Oracle using dotnet user-secrets " +
        "or ConnectionStrings__Oracle.");
}

// Builds the application using the registered services and configuration.
var app = builder.Build();

// Adds middleware that handles otherwise unhandled request exceptions.
//
// It is registered before the endpoints so it can catch exceptions
// raised while those endpoints execute.
//
// handler.Run defines the response generated by the error handler;
// this is different from app.Run(), which starts the application below.
app.UseExceptionHandler(handler => handler.Run(async context =>
{
    // context represents the current HTTP request and response.
    //
    // Read the exception captured by the exception middleware.
    // ?. returns null if the exception feature is unavailable.
    var error = context.Features
        .Get<IExceptionHandlerFeature>()?.Error;

    // Match the exception against known Oracle errors.
    //
    // A switch expression selects a value.
    // Each selected value is a tuple: (HTTP status, error title).
    //
    // Deconstruction stores those values in status and title.
    var (status, title) = error switch
    {
        // ORA-02291: a referenced parent key does not exist.
        //
        // In this application, the message assumes the missing
        // reference is a product or department.
        //
        // HTTP 400 = invalid request.
        OracleException { Number: 2291 } =>
            (400, "The product or department does not exist."),

        // ORA-02290: a CHECK constraint was violated.
        // ORA-01400: NULL was inserted into a required database column.
        // ORA-01438: a number exceeded the column's allowed precision.
        //
        // "or" lets any of these error numbers match this branch.
        OracleException { Number: 2290 or 1400 or 1438 } =>
            (400, "The order violates a database validation rule."),

        // ORA-08177: the transaction could not be serialized.
        // ORA-00060: a deadlock was detected.
        //
        // HTTP 409 = conflict.
        //
        // These errors indicate transaction conflicts; they do not
        // necessarily mean this specific order was edited.
        OracleException { Number: 8177 or 60 } =>
            (409, "The order was changed concurrently. Reload and retry."),

        // _ is the fallback for anything not matched above.
        //
        // HTTP 500 = unexpected server error.
        // Internal exception details are not included in this response.
        _ => (500, "An unexpected error occurred.")
    };

    // Create a standardized Problem Details response using the chosen
    // status code and title, then write it to the HTTP response.
    await Results.Problem(
        statusCode: status,
        title: title
    ).ExecuteAsync(context);
}));

// Expose the OpenAPI document only in the Development environment.
//
// The default document route is /openapi/v1.json.
// This condition controls documentation exposure, not the API endpoints.
if (app.Environment.IsDevelopment())
{
    app.MapOpenApi();
}

// Maps controller actions to their routes.
//
// Examples from your controllers:
//   GET  /api/orders
//   POST /api/orders
//   GET  /api/products
//   GET  /api/reports/order-exceptions
app.MapControllers();

// Starts the web application and waits until it shuts down.
app.Run();